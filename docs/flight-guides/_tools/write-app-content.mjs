/**
 * Compiles the reviewed guide package into modules the APP can import.
 *
 * WHY GENERATE INSTEAD OF RETYPING. The package under docs/flight-guides
 * is the reviewed artefact: its numbers were traced to Betaflight
 * sources, its pictures were checked against the state of the control
 * itself, and its QA gate refuses to pass if any of that drifts. Typing
 * the same values a second time inside src/ would create a copy nobody
 * checks, and the copy would be wrong within a release. So the screens
 * read from here, and here is written from there.
 *
 * WHAT INDEPENDENCE MEANS IN THIS FILE. The output lists five corners in
 * one array because the index screen needs a directory to render - a
 * directory is not a mixed guide. Every VALUE, step, decision and warning
 * stays attached to the single corner it came from, and no screen ever
 * renders two corners' content together. Sharing the reader's screen is
 * what was forbidden; sharing a type definition was never the point.
 *
 * THREE OUTPUTS, because bundlers disagree about images:
 *   guideContent.ts        the text: identity, steps, decisions, warnings
 *   guideImages.ts         Metro/Jest - require() returns an asset id
 *   guideImages.web.ts     Vite - the import returns a URL string
 * The same seam the brand logo already uses (src/ui/brand/brandLogo*).
 *
 * Usage: node docs/flight-guides/_tools/write-app-content.mjs
 */
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {STYLES, IMAGE_ROOT, DECISIONS} from './guide-spec.mjs';

const OUT = 'src/ui/flight-guides';
const BANNER = `/**
 * GENERATED by docs/flight-guides/_tools/write-app-content.mjs.
 * Do not edit by hand: the reviewed source is docs/flight-guides/, and
 * this file is rewritten from it. Change a value there, run the tool.
 */
`;

const quote = text => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;

/** The safety block each guide.md ends with, as plain sentences. */
function warningsOf(styleId) {
  const markdown = readFileSync(`${IMAGE_ROOT}/${styleId}/guide.md`, 'utf8');
  const section = markdown.split(/^## تحذيرات\s*$/m)[1];
  if (section === undefined) return [];
  const body = section.split(/^## /m)[0];
  return body
    .split(/\n\s*\n/)
    .map(block => block.split('\n').map(line => line.replace(/^>\s?/, '').trim()).join(' ').trim())
    .filter(block => block.length > 0 && !block.startsWith('---'));
}

/**
 * A picture's true pixel size, read from the PNG's own IHDR chunk.
 *
 * Carried into the app so every frame can reserve the EXACT aspect ratio
 * before the image decodes. That is what keeps a capture from being
 * stretched or letterboxed, and it stops the page jumping as each one
 * arrives.
 */
function pngSize(path) {
  const head = readFileSync(path).subarray(16, 24);
  return {w: head.readUInt32BE(0), h: head.readUInt32BE(4)};
}

/** The values a step's picture is proven to be holding. */
function recommended(step) {
  const shown = step.targets
    .filter(t => t.kind === 'stepper' || t.kind === 'input')
    .map(t => t.expect);
  const options = step.targets.filter(t => t.kind === 'option' && t.expect === 'selected').length;
  const switches = step.targets.filter(t => t.kind === 'switch' && t.expect === 'on').length;
  const extra = [];
  if (options > 0) extra.push(`${options} خيار محدَّد`);
  if (switches > 0) extra.push(`${switches} مفتاح مفعّل`);
  return [...shown, ...extra];
}

/* ------------------------------------------------------------ content */

const corners = STYLES.map(style => {
  const meta = JSON.parse(readFileSync(`${IMAGE_ROOT}/${style.id}/guide.json`, 'utf8'));
  return {
    id: style.id,
    kind: meta.kind,
    titleAr: meta.title_ar,
    titleEn: meta.title_en,
    descriptionAr: meta.description_ar,
    difficultyAr: meta.difficulty_ar,
    aircraft: meta.intended_aircraft ?? [],
    verification: meta.verification_level,
    hardwareStatus: meta.hardware_verification_status,
    steps: style.steps.map(step => ({
      n: step.n,
      titleAr: step.titleAr,
      screen: step.screen,
      recommended: recommended(step),
      sources: [...new Set(step.targets.map(t => t.source).filter(s => s && s !== 'C'))],
      note: step.note ?? null,
      size: pngSize(`${IMAGE_ROOT}/${style.id}/images/${step.n}-${step.shot}.png`),
    })),
    decisions: (DECISIONS[style.id] ?? []).map(d => ({
      what: d.what, kind: d.kind, detail: d.detail, source: d.source ?? null,
    })),
    warnings: warningsOf(style.id),
  };
});

const list = value => `[${value.map(quote).join(', ')}]`;

const contentSource = `${BANNER}
/** The five flight styles, plus the firmware card, in reading order. */
export type FlightStyleId =
${corners.map(c => `  | ${quote(c.id)}`).join('\n')};

export type GuideStep = {
  readonly n: number;
  readonly titleAr: string;
  /** Where in the app this step is performed. */
  readonly screen: string;
  /** What the picture is proven to be showing. */
  readonly recommended: readonly string[];
  readonly sources: readonly string[];
  readonly note: string | null;
  /** True pixel size of this step's capture, so a frame can reserve its
   *  exact aspect ratio instead of guessing and cropping. */
  readonly width: number;
  readonly height: number;
};

/**
 * A verdict on a requirement this corner's steps do NOT change, so a
 * reader never has to wonder whether a setting was forgotten.
 */
export type GuideDecisionKind =
  | 'STEP' | 'ACTION' | 'PILOT_PREFERENCE' | 'KEEP_DEFAULT' | 'NOT_APPLICABLE';

export type GuideDecision = {
  readonly what: string;
  readonly kind: GuideDecisionKind;
  readonly detail: string;
  readonly source: string | null;
};

export type GuideCorner = {
  readonly id: FlightStyleId;
  /** 'FLIGHT_STYLE' or the firmware card, which is not a flight style. */
  readonly kind: string;
  readonly titleAr: string;
  readonly titleEn: string;
  readonly descriptionAr: string;
  readonly difficultyAr: string;
  readonly aircraft: readonly string[];
  readonly verification: string;
  readonly hardwareStatus: string;
  readonly steps: readonly GuideStep[];
  readonly decisions: readonly GuideDecision[];
  readonly warnings: readonly string[];
};

export const GUIDE_CORNERS: readonly GuideCorner[] = [
${corners.map(c => `  {
    id: ${quote(c.id)},
    kind: ${quote(c.kind)},
    titleAr: ${quote(c.titleAr)},
    titleEn: ${quote(c.titleEn)},
    descriptionAr: ${quote(c.descriptionAr)},
    difficultyAr: ${quote(c.difficultyAr)},
    aircraft: ${list(c.aircraft)},
    verification: ${quote(c.verification)},
    hardwareStatus: ${quote(c.hardwareStatus)},
    steps: [
${c.steps.map(s => `      {
        n: ${s.n},
        titleAr: ${quote(s.titleAr)},
        screen: ${quote(s.screen)},
        recommended: ${list(s.recommended)},
        sources: ${list(s.sources)},
        note: ${s.note === null ? 'null' : quote(s.note)},
        width: ${s.size.w},
        height: ${s.size.h},
      },`).join('\n')}
    ],
    decisions: [
${c.decisions.map(d => `      {what: ${quote(d.what)}, kind: ${quote(d.kind)}, detail: ${quote(d.detail)}, source: ${d.source === null ? 'null' : quote(d.source)}},`).join('\n')}
    ],
    warnings: ${list(c.warnings)},
  },`).join('\n')}
];

/** Flight styles only - the firmware card is a technical section. */
export const FLIGHT_STYLES: readonly GuideCorner[] =
  GUIDE_CORNERS.filter(corner => corner.kind === 'FLIGHT_STYLE');

export function findCorner(id: string): GuideCorner | undefined {
  return GUIDE_CORNERS.find(corner => corner.id === id);
}
`;

/* ------------------------------------------------------------- images */

const shots = STYLES.flatMap(style => style.steps.map(step => ({
  key: `${style.id}/${step.n}`,
  ident: `${style.id.replace(/-([a-z])/g, (_m, c) => c.toUpperCase())}${step.n}`,
  path: `../../../${IMAGE_ROOT}/${style.id}/images/${step.n}-${step.shot}.png`,
})));

const nativeImages = `${BANNER}
/**
 * THE STEP PICTURES - Metro/Jest resolution.
 *
 * require() of a .png registers a real bundled asset, exactly as
 * src/ui/brand/brandLogoSource.ts does for the logo. tsconfig.web.json
 * excludes this file; Vite resolves the .web sibling instead.
 *
 * The files are NOT copied into src/. They are the reviewed captures in
 * docs/flight-guides/<style>/images/, and a second copy would be a
 * second thing to keep true.
 */

import type {ImageSourcePropType} from 'react-native';

export const GUIDE_STEP_IMAGES: Readonly<Record<string, ImageSourcePropType>> = {
${shots.map(s => `  '${s.key}': require('${s.path}') as ImageSourcePropType,`).join('\n')}
};
`;

const webImages = `${BANNER}
/**
 * THE STEP PICTURES - browser resolution.
 *
 * Vite resolves this file instead of guideImages.ts and serves each
 * capture as a hashed static asset: the exact committed bytes, decoded
 * by the browser, downloaded only when the corner that shows them is
 * opened.
 */

import type {ImageSourcePropType} from 'react-native';

${shots.map(s => `import ${s.ident} from '${s.path}';`).join('\n')}

export const GUIDE_STEP_IMAGES: Readonly<Record<string, ImageSourcePropType>> = {
${shots.map(s => `  '${s.key}': {uri: ${s.ident}},`).join('\n')}
};
`;

mkdirSync(OUT, {recursive: true});
writeFileSync(`${OUT}/guideContent.ts`, contentSource, 'utf8');
writeFileSync(`${OUT}/guideImages.ts`, nativeImages, 'utf8');
writeFileSync(`${OUT}/guideImages.web.ts`, webImages, 'utf8');

console.log(`${corners.length} corners · ${shots.length} step pictures`);
for (const c of corners) {
  console.log(`  ${c.id.padEnd(12)} ${c.steps.length} steps · ${c.decisions.length} decisions · ${c.warnings.length} warnings`);
}
