/**
 * Writes the ordered "خطوات الضبط" section into each guide.md, and the
 * matching `steps` array into each guide.json, from the spec.
 *
 * Both artefacts are GENERATED between markers, so guide.md and
 * guide.json cannot disagree about the order, the values, the screens or
 * the pictures - the failure the owner review found.
 *
 * Usage: node docs/flight-guides/_tools/write-steps.mjs
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {STYLES, IMAGE_ROOT} from './guide-spec.mjs';

const BEGIN = '<!-- STEPS:BEGIN generated by _tools/write-steps.mjs -->';
const END = '<!-- STEPS:END -->';

/** The values a step's picture is proven to be showing. */
function values(step) {
  return step.targets
    .filter(t => t.kind === 'stepper' || t.kind === 'input')
    .map(t => `\`${t.expect}\``)
    .join(' · ');
}
function selected(step) {
  const chips = step.targets.filter(t => t.kind === 'option' && t.expect === 'selected').length;
  const toggles = step.targets.filter(t => t.kind === 'switch' && t.expect === 'on').length;
  const parts = [];
  if (chips > 0) parts.push(`${chips} خيار محدَّد`);
  if (toggles > 0) parts.push(`${toggles} مفتاح مفعّل`);
  return parts.join(' · ');
}

for (const style of STYLES) {
  const lines = [
    BEGIN,
    '',
    '## خطوات الضبط — بالترتيب',
    '',
    'اتبعها من الأولى إلى الأخيرة. كل خطوة تُظهر الشاشة نفسها بالقيم',
    'الموصى بها في هذا الدليل، لا بقيم نمط آخر.',
    '',
  ];

  for (const step of style.steps) {
    const v = values(step);
    const s = selected(step);
    const sources = [...new Set(step.targets.map(t => t.source).filter(x => x && x !== 'C'))];
    lines.push(`### الخطوة ${step.n} — ${step.titleAr}`);
    lines.push('');
    lines.push(`**أين:** ${step.screen}`);
    if (v !== '' || s !== '') {
      lines.push('');
      lines.push(`**الموصى به:** ${[v, s].filter(Boolean).join(' · ')}${sources.length > 0 ? `  ·  المصدر: ${sources.join('، ')}` : ''}`);
    }
    lines.push('');
    lines.push(`![${step.titleAr} — ${step.screen}](images/${step.n}-${step.shot}.png)`);
    lines.push('');
  }

  lines.push('> كل صورة أعلاه مأخوذة من بناء التطبيق الحالي، ومفحوصة آليًا على');
  lines.push('> **حالة عنصر التحكم نفسه** — القيمة داخل الحقل، والخيار المحدَّد،');
  lines.push('> والمفتاح المفعّل — لا على مجرد ظهور النص في الصورة.');
  lines.push('');
  lines.push(END);

  const generated = lines.join('\n');
  const path = `${IMAGE_ROOT}/${style.id}/guide.md`;
  let markdown = readFileSync(path, 'utf8');
  if (markdown.includes(BEGIN)) {
    markdown = markdown.replace(
      new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`),
      generated,
    );
  } else {
    // First run: replace the old ad-hoc screen table, or a placeholder.
    if (markdown.includes('<!-- STEPS:PLACEHOLDER -->')) {
      markdown = markdown.replace('<!-- STEPS:PLACEHOLDER -->', generated);
    } else {
      markdown = markdown.replace(/## أين تضبط كل شيء[\s\S]*?(?=\n---\n)/, `${generated}\n\n`);
    }
  }
  writeFileSync(path, markdown, 'utf8');

  const jsonPath = `${IMAGE_ROOT}/${style.id}/guide.json`;
  const meta = JSON.parse(readFileSync(jsonPath, 'utf8'));
  meta.steps = style.steps.map(step => ({
    n: step.n,
    title_ar: step.titleAr,
    screen: step.screen,
    screenshot: `images/${step.n}-${step.shot}.png`,
    targets: step.targets.map(t => ({
      control: t.testid, kind: t.kind, expected: t.expect, source: t.source,
    })),
  }));
  meta.step_count = style.steps.length;
  writeFileSync(jsonPath, `${JSON.stringify(meta, null, 2)}\n`, 'utf8');

  console.log(`${style.id.padEnd(12)} ${style.steps.length} steps written to guide.md + guide.json`);
}
