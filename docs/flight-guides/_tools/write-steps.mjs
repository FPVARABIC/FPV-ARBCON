/**
 * Writes the ordered "خطوات الضبط" section into each guide.md, and the
 * matching `steps` array into each guide.json, from the spec.
 *
 * Both artefacts are GENERATED between markers, so guide.md and
 * guide.json cannot disagree about the order, the values, the screens or
 * the pictures - the failure the owner review found.
 *
 * Usage: node docs/flight-guides/_tools/write-steps.mjs
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {STYLES, DECISIONS, IMAGE_ROOT} from './guide-spec.mjs';

const BEGIN = '<!-- STEPS:BEGIN generated by _tools/write-steps.mjs -->';
const END = '<!-- STEPS:END -->';

/** The values a step's picture is proven to be showing. */
function values(step) {
  return step.targets
    .filter(t => t.kind === 'stepper' || t.kind === 'input')
    .map(t => `\`${t.expect}\``)
    .join(' · ');
}
function selected(step) {
  const chips = step.targets.filter(t => t.kind === 'option' && t.expect === 'selected').length;
  const toggles = step.targets.filter(t => t.kind === 'switch' && t.expect === 'on').length;
  const parts = [];
  if (chips > 0) parts.push(`${chips} is een gespecificeerde optie.`);
  if (toggles > 0) parts.push(`${toggles} is geactiveerd.`);
  return parts.join(' · ');
}

for (const style of STYLES) {
  const lines = [
    BEGIN,
    '',
    "De stapjes in de volgorde",
    '',
    "Volg haar van het eerste tot het laatste. Elke stap geeft het scherm dezelfde waarden.",
    "Aanbevolen in deze handleiding, geen andere stijlwaarden.",
    '',
  ];

  for (const step of style.steps) {
    const v = values(step);
    const s = selected(step);
    const sources = [...new Set(step.targets.map(t => t.source).filter(x => x && x !== 'C'))];
    lines.push(`Stap ${step.n}  —  ${step.titleAr}`);
    lines.push('');
    lines.push(`${step.screen}.`);
    if (v !== '' || s !== '') {
      lines.push('');
      lines.push(`Aanbevolen: ${[v, s].filter(Boolean).join(' · ')}${sources.length > 0 ? `· Bron: ${sources.join(", ")}` : ''}`);
    }
    lines.push('');
    lines.push(`![${step.titleAr} — ${step.screen}](images/${step.n}-${step.shot}.png)`);
    lines.push('');
    if (step.note !== undefined) {
      lines.push(step.note);
      lines.push('');
    }
  }

  lines.push("Alle foto's hierboven zijn afkomstig van de bouw van de huidige app, en worden automatisch gecontroleerd op");
  lines.push("De waarde binnen het veld, de gespecificeerde optie,");
  lines.push("De actieve sleutel is niet alleen het verschijnen van de tekst in de foto.");
  lines.push('');

  /* Everything the steps do NOT change still gets a verdict here, so a
   * reader never has to wonder whether we forgot a setting - or open
   * another style's corner to find out what we decided. */
  const LABEL = {
    STEP: "Stap",
    ACTION: "Procedure  —  zonder foto",
    PILOT_PREFERENCE: "Voorkeur van de piloot",
    KEEP_DEFAULT: "Ongewijzigd laten",
    NOT_APPLICABLE: "Niet van toepassing",
  };
  const decisions = DECISIONS[style.id] ?? [];
  lines.push('---');
  lines.push('');
  lines.push("De rest van de instellingen is een keuze voor iedereen.");
  lines.push('');
  lines.push("Alles wat de stappen hierboven niet veranderen, heeft hier een besluit geschreven, zodat je niet blijft.");
  lines.push("Je vraagt je af of we hem vergeten zijn. De beslissingen zijn alleen van deze stijl.");
  lines.push('');
  lines.push("De voorbereiding, de beslissing, de details, de bron.");
  lines.push('|---|---|---|---|');
  for (const d of decisions) {
    lines.push(`| ${d.what} | **${LABEL[d.kind]}** | ${d.detail} | ${d.source ?? '—'} |`);
  }
  lines.push('');
  lines.push(END);

  const generated = lines.join('\n');
  const path = `${IMAGE_ROOT}/${style.id}/guide.md`;
  let markdown = readFileSync(path, 'utf8');
  if (markdown.includes(BEGIN)) {
    markdown = markdown.replace(
      new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`),
      generated,
    );
  } else {
    // First run: replace the old ad-hoc screen table, or a placeholder.
    if (markdown.includes('<!-- STEPS:PLACEHOLDER -->')) {
      markdown = markdown.replace('<!-- STEPS:PLACEHOLDER -->', generated);
    } else {
      markdown = markdown.replace(/## أين تضبط كل شيء[\s\S]*?(?=\n---\n)/, `${generated}\n\n`);
    }
  }
  writeFileSync(path, markdown, 'utf8');

  const jsonPath = `${IMAGE_ROOT}/${style.id}/guide.json`;
  const meta = JSON.parse(readFileSync(jsonPath, 'utf8'));
  meta.steps = style.steps.map(step => ({
    n: step.n,
    title_ar: step.titleAr,
    screen: step.screen,
    screenshot: `images/${step.n}-${step.shot}.png`,
    targets: step.targets.map(t => ({
      control: t.testid, kind: t.kind, expected: t.expect, source: t.source,
    })),
  }));
  meta.step_count = style.steps.length;
  meta.decisions = (DECISIONS[style.id] ?? []).map(d => ({
    requirement: d.what, decision: d.kind, detail: d.detail, source: d.source ?? null,
  }));
  writeFileSync(jsonPath, `${JSON.stringify(meta, null, 2)}\n`, 'utf8');

  console.log(`${style.id.padEnd(12)} ${style.steps.length} steps written to guide.md + guide.json`);
}
